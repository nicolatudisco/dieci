#!/usr/bin/env node
/**
 * Fetches the distance of Voyager 1 from the Earth from NASA/JPL Horizons and writes it as
 * a table in src/content/voyager-distance.ts. Run it once, by hand, from the project root:
 *
 *   node scripts/voyager-horizons.mjs
 *
 * The site never talks to the network at runtime: the table is committed and interpolated
 * (src/voyager.ts). Run the script again only to extend the table or after JPL publishes a
 * new trajectory; `npm test` then checks the table against the light-day moment in data.ts.
 *
 * What is asked for: the GEOMETRIC distance between the centre of the Earth and the probe
 * (no light-time correction: where Voyager is «in questo momento», not where we see it),
 * one value every two days. Two days because the Earth also swings around its common
 * centre with the Moon every 27 days: with this step a cubic interpolation stays within
 * about 10 km of Horizons.
 */
import fs from 'node:fs';
import path from 'node:path';

const START = '2026-01-01';
const STOP = '2041-01-01';
const STEP_DAYS = 2;
const OUT = path.resolve('src/content/voyager-distance.ts');

/**
 * Horizons gives vector tables in Barycentric Dynamical Time. TDB - UTC = 32.184 s + 37 leap
 * seconds (unchanged since 2017). Leap seconds added after today cannot be known: each one
 * would move the table by about 25 km.
 */
const TDB_MINUS_UTC_MS = 69_184;
const UNIX_EPOCH_JD = 2_440_587.5;
const DAY_MS = 86_400_000;

const params = new URLSearchParams({
  format: 'text',
  COMMAND: "'-31'", // Voyager 1
  OBJ_DATA: "'NO'",
  MAKE_EPHEM: "'YES'",
  EPHEM_TYPE: "'VECTORS'",
  CENTER: "'500@399'", // centre of the Earth
  START_TIME: `'${START}'`,
  STOP_TIME: `'${STOP}'`,
  STEP_SIZE: `'${STEP_DAYS} d'`,
  VEC_TABLE: "'6'", // light-time, range, range-rate
  VEC_CORR: "'NONE'", // geometric
  OUT_UNITS: "'KM-S'",
  CSV_FORMAT: "'YES'",
});

const response = await fetch(`https://ssd.jpl.nasa.gov/api/horizons.api?${params}`);
if (!response.ok) throw new Error(`Horizons answered ${response.status}`);
const text = await response.text();

const body = /\$\$SOE\n([\s\S]*?)\n\$\$EOE/.exec(text)?.[1];
if (!body) throw new Error(`No ephemeris in the answer:\n${text.slice(0, 2000)}`);
const trajectory = /Target body name:.*\{source: ([^}]+)\}/.exec(text)?.[1] ?? 'unknown';

const rows = body
  .split('\n')
  .map((line) => line.split(',').map((cell) => cell.trim()))
  .map((cells) => ({ jd: Number(cells[0]), km: Number(cells[3]) }));
if (rows.some((row) => !Number.isFinite(row.jd) || !Number.isFinite(row.km))) throw new Error('Unreadable row in the ephemeris');
for (let i = 1; i < rows.length; i++) {
  if (Math.abs(rows[i].jd - rows[i - 1].jd - STEP_DAYS) > 1e-6) throw new Error(`Uneven step at row ${i}`);
}

const startMs = Math.round((rows[0].jd - UNIX_EPOCH_JD) * DAY_MS) - TDB_MINUS_UTC_MS;
const km = rows.map((row) => Math.round(row.km));
const lines = [];
for (let i = 0; i < km.length; i += 8) lines.push(`    ${km.slice(i, i + 8).join(', ')},`);

const today = new Date().toISOString().slice(0, 10);
const source = `/**
 * GENERATED by scripts/voyager-horizons.mjs: do not edit by hand.
 *
 * Distance of Voyager 1 from the centre of the Earth, in km, every ${STEP_DAYS} days from
 * ${START} to ${STOP}. Geometric (no light-time correction).
 * Source: NASA/JPL Horizons (https://ssd.jpl.nasa.gov/horizons/), trajectory
 * «${trajectory}», fetched on ${today}.
 */
export const VOYAGER_1_DISTANCE: { readonly startMs: number; readonly stepMs: number; readonly km: readonly number[] } = {
  /** UTC instant of the first sample, in milliseconds since the Unix epoch. */
  startMs: ${startMs},
  /** Time between two samples, in milliseconds. */
  stepMs: ${STEP_DAYS * DAY_MS},
  km: [
${lines.join('\n')}
  ],
};
`;
fs.writeFileSync(OUT, source);
console.log(`${km.length} samples, ${new Date(startMs).toISOString()} → ${new Date(startMs + (km.length - 1) * STEP_DAYS * DAY_MS).toISOString()}`);
console.log(`trajectory: ${trajectory}`);
console.log(`written: ${path.relative(process.cwd(), OUT)} (${(source.length / 1024).toFixed(1)} kB)`);
