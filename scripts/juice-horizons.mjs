#!/usr/bin/env node
/**
 * Fetches where the ESA probe Juice is, on its way to Jupiter, from NASA/JPL Horizons and
 * writes it as a table in src/content/juice-position.ts. Run it once, by hand, from the
 * project root:
 *
 *   node scripts/juice-horizons.mjs
 *
 * The site never talks to the network at runtime: the table is committed and interpolated
 * (src/juice.ts). In the scene of `giove` the planets are placed along their orbits by
 * composition, except the Earth, whose place is fixed by the stage; so what matters is where
 * Juice is SEEN FROM THE SUN COMPARED WITH THE EARTH. Each row is Juice in a frame that turns
 * with the Earth: the Sun in the middle, the Earth always on the +x axis, the plane of the
 * ecliptic, astronomical units.
 *
 * Horizons has the trajectory up to the arrival at Jupiter (21 July 2031): after that the
 * probe is in orbit around Jupiter, and the scene draws it there.
 */
import fs from 'node:fs';
import path from 'node:path';

const START = '2026-01-01';
const STOP = '2031-07-20';
const STEP_DAYS = 5;
const OUT = path.resolve('src/content/juice-position.ts');

const TDB_MINUS_UTC_MS = 69_184;
const UNIX_EPOCH_JD = 2_440_587.5;
const DAY_MS = 86_400_000;

async function vectors(command) {
  const params = new URLSearchParams({
    format: 'text',
    COMMAND: `'${command}'`,
    OBJ_DATA: "'NO'",
    MAKE_EPHEM: "'YES'",
    EPHEM_TYPE: "'VECTORS'",
    CENTER: "'500@10'", // the Sun
    REF_PLANE: "'ECLIPTIC'",
    START_TIME: `'${START}'`,
    STOP_TIME: `'${STOP}'`,
    STEP_SIZE: `'${STEP_DAYS} d'`,
    VEC_TABLE: "'1'", // positions only
    VEC_CORR: "'NONE'",
    OUT_UNITS: "'AU-D'",
    CSV_FORMAT: "'YES'",
  });
  const response = await fetch(`https://ssd.jpl.nasa.gov/api/horizons.api?${params}`);
  if (!response.ok) throw new Error(`Horizons answered ${response.status}`);
  const text = await response.text();
  const body = /\$\$SOE\n([\s\S]*?)\n\$\$EOE/.exec(text)?.[1];
  if (!body) throw new Error(`No ephemeris in the answer:\n${text.slice(0, 2000)}`);
  const source = /Target body name:.*\{source: ([^}]+)\}/.exec(text)?.[1] ?? 'unknown';
  const rows = body
    .split('\n')
    .map((line) => line.split(',').map((cell) => cell.trim()))
    .map((cells) => ({ jd: Number(cells[0]), x: Number(cells[2]), y: Number(cells[3]) }));
  if (rows.some((r) => !Number.isFinite(r.jd) || !Number.isFinite(r.x) || !Number.isFinite(r.y))) throw new Error('Unreadable row');
  return { rows, source };
}

const juice = await vectors('-28');
const earth = await vectors('399');
if (juice.rows.length !== earth.rows.length) throw new Error('The two tables do not line up');

const values = [];
for (let i = 0; i < juice.rows.length; i++) {
  const j = juice.rows[i];
  const e = earth.rows[i];
  if (Math.abs(j.jd - e.jd) > 1e-6) throw new Error(`Rows ${i} are not at the same time`);
  if (i > 0 && Math.abs(j.jd - juice.rows[i - 1].jd - STEP_DAYS) > 1e-6) throw new Error(`Uneven step at row ${i}`);
  // Turn the frame so that the Earth lies on +x.
  const a = Math.atan2(e.y, e.x);
  const x = j.x * Math.cos(a) + j.y * Math.sin(a);
  const y = -j.x * Math.sin(a) + j.y * Math.cos(a);
  values.push(Math.round(x * 1e4) / 1e4, Math.round(y * 1e4) / 1e4);
}

const startMs = Math.round((juice.rows[0].jd - UNIX_EPOCH_JD) * DAY_MS) - TDB_MINUS_UTC_MS;
const lines = [];
for (let i = 0; i < values.length; i += 12) lines.push(`    ${values.slice(i, i + 12).join(', ')},`);
const today = new Date().toISOString().slice(0, 10);
const source = `/**
 * GENERATED by scripts/juice-horizons.mjs: do not edit by hand.
 *
 * Where the probe Juice is, seen from the Sun, in a frame that turns with the Earth (the Earth
 * always on +x, the plane of the ecliptic), in astronomical units: pairs x, y every
 * ${STEP_DAYS} days from ${START} to ${STOP}, just before the arrival at Jupiter.
 * Source: NASA/JPL Horizons (https://ssd.jpl.nasa.gov/horizons/), trajectory
 * «${juice.source}», fetched on ${today}.
 */
export const JUICE_POSITION: { readonly startMs: number; readonly stepMs: number; readonly xy: readonly number[] } = {
  /** UTC instant of the first sample, in milliseconds since the Unix epoch. */
  startMs: ${startMs},
  /** Time between two samples, in milliseconds. */
  stepMs: ${STEP_DAYS * DAY_MS},
  xy: [
${lines.join('\n')}
  ],
};
`;
fs.writeFileSync(OUT, source);
console.log(`${values.length / 2} samples, ${new Date(startMs).toISOString()} → ${new Date(startMs + (values.length / 2 - 1) * STEP_DAYS * DAY_MS).toISOString()}`);
console.log(`trajectory: ${juice.source}`);
console.log(`written: ${path.relative(process.cwd(), OUT)} (${(source.length / 1024).toFixed(1)} kB)`);
