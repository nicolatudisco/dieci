#!/usr/bin/env node
/**
 * The coasts of the Earth for the picture «La Terra vista dallo spazio» of the Golden Record
 * lab: Natural Earth land (1:10m, public domain) seen from space above Africa, in an
 * orthographic projection, simplified to a few hundred points on a 100 × 100 grid.
 *
 * Run once, from the project root (it needs the Natural Earth file that
 * scripts/geodata/build.mjs keeps in its cache):
 *   node scripts/golden-record-earth.mjs
 * It writes src/golden-record/earth-outline.ts, which is committed.
 *
 * The view has nothing to do with the starting point of the journey: it is a round point
 * over the Sahara, from where Europe, Africa and Arabia are all in sight, like the photos
 * of the whole Earth taken by the astronauts.
 */
import fs from 'node:fs';
import path from 'node:path';
import { CACHE, ROOT, ringArea, simplify } from './geodata/common.mjs';

const SOURCE = path.join(CACHE, 'ne_10m_land.geojson');
const OUT = path.join(ROOT, 'src', 'golden-record', 'earth-outline.ts');

/** The point of the Earth at the centre of the picture. */
const CENTRE = { lat: 20, lon: 15 };
/** The globe on the grid: centre and radius. */
const C = 50;
const R = 44;
/** Simplification, in grid units, and the smallest island kept (grid units²). */
const TOLERANCE = 0.32;
const MIN_AREA = 0.9;

if (!fs.existsSync(SOURCE)) {
  console.error(`Manca ${path.relative(ROOT, SOURCE)}: eseguire prima scripts/geodata/build.mjs, che lo scarica.`);
  process.exit(1);
}

const RAD = Math.PI / 180;
const lat0 = CENTRE.lat * RAD;
const lon0 = CENTRE.lon * RAD;

/** Grid point of a place, and whether it is on the side we see. */
function project([lon, lat]) {
  const p = lat * RAD;
  const l = lon * RAD - lon0;
  const visible = Math.sin(lat0) * Math.sin(p) + Math.cos(lat0) * Math.cos(p) * Math.cos(l);
  const x = Math.cos(p) * Math.sin(l);
  const y = Math.cos(lat0) * Math.sin(p) - Math.sin(lat0) * Math.cos(p) * Math.cos(l);
  return { x: C + R * x, y: C - R * y, visible: visible > 0.02 };
}

const land = JSON.parse(fs.readFileSync(SOURCE, 'utf8'));
const rings = [];
for (const feature of land.features) {
  const g = feature.geometry;
  const polygons = g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : [];
  for (const polygon of polygons) for (const ring of polygon) rings.push(ring);
}

/** Coastlines as open lines: a ring is cut where it goes behind the Earth. */
const lines = [];
for (const ring of rings) {
  let current = [];
  const flush = () => {
    if (current.length > 1) lines.push(current);
    current = [];
  };
  for (const point of ring) {
    const p = project(point);
    if (p.visible) current.push([p.x, p.y]);
    else flush();
  }
  flush();
}

/** Lines that close on themselves are rings again (islands, whole coasts). */
const closed = (line) => {
  const a = line[0];
  const b = line[line.length - 1];
  return Math.hypot(a[0] - b[0], a[1] - b[1]) < 1e-6;
};

const kept = [];
for (const line of lines) {
  if (closed(line) && Math.abs(ringArea(line)) < MIN_AREA) continue;
  const simple = simplify(line, TOLERANCE);
  if (simple.length < 2) continue;
  const length = simple.slice(1).reduce((sum, p, i) => sum + Math.hypot(p[0] - simple[i][0], p[1] - simple[i][1]), 0);
  if (length < 1.2) continue;
  kept.push(simple);
}

const f = (n) => String(Math.round(n * 10) / 10);
const paths = kept.map((line) => line.map((p, i) => `${i ? 'L' : 'M'}${f(p[0])} ${f(p[1])}`).join('') + (closed(line) ? 'Z' : ''));
const points = kept.reduce((sum, line) => sum + line.length, 0);

const source = `/**
 * The coasts of the Earth seen from space above Africa (${CENTRE.lat}° N, ${CENTRE.lon}° E), on a
 * 100 × 100 grid with the globe centred at (${C}, ${C}) and radius ${R}: SVG path data.
 * Generated by scripts/golden-record-earth.mjs from Natural Earth (1:10m land, public
 * domain). Do not edit by hand.
 */
export const EARTH_CENTRE = { x: ${C}, y: ${C}, r: ${R} } as const;

export const EARTH_COASTS: readonly string[] = ${JSON.stringify(paths, null, 2)};
`;
fs.writeFileSync(OUT, source);
console.log(`${path.relative(ROOT, OUT)}: ${paths.length} linee, ${points} punti, ${(source.length / 1024).toFixed(1)} kB`);
